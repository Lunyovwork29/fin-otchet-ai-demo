HEADERS = ["Дата", "Контрагент", "Назначение платежа", "Сумма, тенге", "Тип"]


def build():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Операции"

    header_fill = PatternFill(start_color="305496", end_color="305496", fill_type="solid")
    header_font = Font(name="Arial", bold=True, color="FFFFFF", size=11)
    thin = Side(style="thin", color="BFBFBF")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    ws.append(HEADERS)
    for col_idx in range(1, len(HEADERS) + 1):
        c = ws.cell(row=1, column=col_idx)
        c.fill = header_fill
        c.font = header_font
        c.alignment = Alignment(horizontal="center", vertical="center")
        c.border = border
    ws.row_dimensions[1].height = 22
    ws.freeze_panes = "A2"

    body_font = Font(name="Arial", size=10)
    for r, row in enumerate(OPERATIONS, start=2):
        ws.append(row)
        for col_idx in range(1, len(HEADERS) + 1):
            c = ws.cell(row=r, column=col_idx)
            c.font = body_font
            c.border = border
            c.alignment = Alignment(vertical="center", horizontal="left" if col_idx in (1, 2, 3, 5) else "right")
        ws.cell(row=r, column=4).number_format = '#,##0" ₸"'
        if row[4] == "доход":
            ws.cell(row=r, column=5).font = Font(name="Arial", size=10, color="1E7B34")
        else:
            ws.cell(row=r, column=5).font = Font(name="Arial", size=10, color="B00020")

    widths = [12, 32, 55, 14, 10]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    ws.sheet_view.showGridLines = False

    out_path = BASE_DIR / "01_iskhodnye_dannye.xlsx"
    wb.save(out_path)
    print(f"Сохранено: {out_path} ({len(OPERATIONS)} операций)")


if __name__ == "__main__":
    build()
